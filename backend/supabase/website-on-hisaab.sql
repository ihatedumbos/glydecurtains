-- Glyde website on the Hisaab Supabase project.
--
-- Run once in Supabase: Dashboard → SQL Editor → New query → paste → replace CHOOSE_A_PASSWORD → Run.
-- Run it AFTER Hisaab's own backend/supabase-setup.sql, and BEFORE the website first starts on this database.
-- Safe to re-run: it only creates what is missing and replaces the views and functions.
--
-- What it does:
--   * A database login for the website (glyde_website) that can only create tables in the "website" schema. It gets no rights on
--     Hisaab's tables; it reaches items and sizes only through the views below, and only for one business.
--   * website.products, website.product_variants and website.product_specifications are views over Hisaab's
--     public.records (kind 'item' and 'variant'). The website reads and writes them like tables; triggers turn
--     each write into a Hisaab record, so phones pick it up at their next sync. Products added in Hisaab show up
--     on the website the same way.
--   * Website-only details live in records.data->'web'. A trigger on public.records keeps them when a phone
--     uploads an item without them (Hisaab sends an item's whole JSON on every change).

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- website login and schema
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'glyde_website') then
    create role glyde_website login password 'CHOOSE_A_PASSWORD';
  end if;
end $$;
-- lets this script hand tables to the website login and read the website's categories
grant glyde_website to postgres;

-- The schema belongs to postgres: the website can create its own tables in it but can't drop the views below.
create schema if not exists website;
alter schema website owner to postgres;
grant usage, create on schema website to glyde_website;
alter role glyde_website set search_path = website;
revoke all on schema public from glyde_website;
revoke all on all tables in schema public from glyde_website;

-- Which Hisaab business the website shows. There is one business in the project; the first one is used.
create table if not exists website.hisaab_link (
  only_row    boolean primary key default true check (only_row),
  business_id uuid not null references public.businesses(id) on delete cascade
);
alter table website.hisaab_link owner to postgres;
insert into website.hisaab_link (business_id)
select id from public.businesses order by created_at limit 1
on conflict (only_row) do nothing;

create or replace function website.biz() returns uuid
language sql stable security definer set search_path = website, public as $$
  select business_id from website.hisaab_link
$$;

-- Website product and size ids (numbers) for Hisaab's record ids (uuids).
create table if not exists website.record_ids (
  id        bigint generated by default as identity primary key,
  record_id uuid not null unique
);
alter table website.record_ids owner to postgres;
create sequence if not exists website.spec_ids;
alter sequence website.spec_ids owner to postgres;

-- Categories stay a website table (icons, order). An item's category is matched by name.
-- Same layout the website would create itself; created here so the views below can use it.
create table if not exists website.categories (
  id           bigint generated by default as identity primary key,
  created_at   timestamp(6) without time zone not null,
  updated_at   timestamp(6) without time zone,
  description  varchar(255),
  icon_base64  text,
  image_base64 text,
  is_active    boolean not null,
  is_visible   boolean not null,
  name         varchar(255) not null unique,
  sort_order   integer not null
);
alter table website.categories owner to glyde_website;

-- ---------------------------------------------------------------- keep website details on phone uploads
create or replace function public.records_keep_web() returns trigger
language plpgsql as $$
begin
  if old.data ? 'web' then
    new.data := jsonb_set(new.data, '{web}', (old.data -> 'web') || coalesce(new.data -> 'web', '{}'::jsonb));
  end if;
  return new;
end $$;
drop trigger if exists records_keep_web on public.records;
create trigger records_keep_web before update on public.records
  for each row when (old.kind in ('item', 'variant')) execute function public.records_keep_web();

-- Every item and size of the business gets a website id as soon as it exists.
create or replace function website.records_assign_id() returns trigger
language plpgsql security definer set search_path = website, public as $$
begin
  if new.kind in ('item', 'variant') and new.business_id = website.biz() then
    insert into website.record_ids (record_id) values (new.id) on conflict (record_id) do nothing;
  end if;
  return null;
end $$;
drop trigger if exists records_website_id on public.records;
create trigger records_website_id after insert on public.records
  for each row execute function website.records_assign_id();

insert into website.record_ids (record_id)
select id from public.records
where business_id = website.biz() and kind in ('item', 'variant')
on conflict (record_id) do nothing;

-- ---------------------------------------------------------------- helpers
create or replace function website.rec_id(p_id bigint) returns uuid
language sql stable security definer set search_path = website, public as $$
  select record_id from website.record_ids where id = p_id
$$;

create or replace function website.web_id(p_record uuid) returns bigint
language sql stable security definer set search_path = website, public as $$
  select id from website.record_ids where record_id = p_record
$$;

create or replace function website.txt(j jsonb, k text) returns text
language sql immutable as $$ select nullif(btrim(j ->> k), '') $$;

create or replace function website.num(j jsonb, k text) returns numeric
language sql immutable as $$
  select case when jsonb_typeof(j -> k) = 'number' then (j ->> k)::numeric
              when (j ->> k) ~ '^-?[0-9]+(\.[0-9]+)?$' then (j ->> k)::numeric end
$$;

create or replace function website.flag(j jsonb, k text, dflt boolean) returns boolean
language sql immutable as $$
  select case when jsonb_typeof(j -> k) = 'boolean' then (j ->> k)::boolean else dflt end
$$;

create or replace function website.ts(t timestamptz) returns timestamp
language sql immutable as $$ select (t at time zone 'UTC')::timestamp $$;

create or replace function website.category_id(p_name text) returns bigint
language sql stable security definer set search_path = website, public as $$
  select id from website.categories where lower(name) = lower(btrim(p_name)) order by id limit 1
$$;

create or replace function website.category_name(p_id bigint) returns text
language sql stable security definer set search_path = website, public as $$
  select name from website.categories where id = p_id
$$;

-- Item prices are paise. Items sold by length keep their price in sale_rate (per rate_unit).
create or replace function website.item_price(d jsonb) returns numeric
language sql immutable as $$
  select round(coalesce(case when website.txt(d, 'rate_unit') is not null then website.num(d, 'sale_rate')
                             else website.num(d, 'sale_price') end, 0) / 100.0, 2)
$$;

-- Writes one record's data for the website's business (as postgres, so Hisaab's own triggers run).
create or replace function website.save_record(p_id uuid, p_kind text, p_data jsonb, p_deleted boolean default false)
returns void
language plpgsql security definer set search_path = website, public as $$
begin
  insert into public.records (id, business_id, kind, data, deleted)
  values (p_id, website.biz(), p_kind, p_data, p_deleted)
  on conflict (id) do update set data = excluded.data, deleted = excluded.deleted
  where records.business_id = website.biz();
end $$;

-- ---------------------------------------------------------------- products = Hisaab items
create or replace view website.products as
select
  i.id                                                          as id,
  coalesce(website.txt(w, 'created_at')::timestamp, website.ts(r.updated_at)) as created_at,
  website.ts(r.updated_at)                                      as updated_at,
  website.txt(d, 'barcode')                                     as barcode,
  website.item_price(d)                                         as base_price,
  website.txt(d, 'brand')                                       as brand,
  website.category_id(d ->> 'category')                         as category_id,
  website.num(w, 'collection_id')::bigint                       as collection_id,
  coalesce(nullif(w ->> 'colors', ''),
           case when website.txt(d, 'color') is not null then jsonb_build_array(d ->> 'color')::text end) as colors,
  website.num(w, 'discount_percentage')                         as discount_percentage,
  website.num(w, 'height')::double precision                    as height,
  website.txt(d, 'name')                                        as internal_name,
  website.flag(w, 'is_best_seller', false)                      as is_best_seller,
  website.flag(w, 'is_featured', false)                         as is_featured,
  website.flag(w, 'is_new_arrival', false)                      as is_new_arrival,
  website.flag(w, 'is_premium', false)                          as is_premium,
  website.flag(w, 'is_trending', false)                         as is_trending,
  website.num(w, 'length')::double precision                    as length,
  website.txt(w, 'long_description')                            as long_description,
  coalesce(website.num(d, 'low_stock'), 0)::integer             as low_stock_threshold,
  website.txt(d, 'material')                                    as material,
  website.txt(w, 'meta_description')                            as meta_description,
  website.txt(w, 'meta_keywords')                               as meta_keywords,
  website.txt(w, 'meta_title')                                  as meta_title,
  coalesce(website.txt(w, 'name'), website.txt(d, 'name'), 'Item')::varchar(200) as name,
  website.num(w, 'offer_price')                                 as offer_price,
  website.txt(w, 'pattern')                                     as pattern,
  website.txt(d, 'description')::varchar(500)                   as short_description,
  nullif(w ->> 'sizes', '')                                     as sizes,
  coalesce(website.txt(d, 'sku'), 'H-' || upper(substr(r.id::text, 1, 8))) as sku,
  case when coalesce(website.num(d, 'active'), 1) = 0 then 'DEACTIVATED'
       when not website.flag(w, 'visible', true) then coalesce(nullif(website.txt(w, 'status'), 'ACTIVE'), 'ARCHIVED')
       else 'ACTIVE' end::varchar(255)                          as status,
  coalesce(website.num(d, 'opening_stock'), 0)::integer         as stock_quantity,
  website.num(w, 'sub_category_id')::bigint                     as sub_category_id,
  website.txt(w, 'tags')                                        as tags,
  website.num(w, 'weight')::double precision                    as weight,
  website.num(w, 'width')::double precision                     as width
from public.records r
join website.record_ids i on i.record_id = r.id
cross join lateral (select r.data as d, coalesce(r.data -> 'web', '{}'::jsonb) as w) x
where r.business_id = website.biz() and r.kind = 'item' and not r.deleted;

create or replace function website.product_data(n website.products, old_data jsonb) returns jsonb
language plpgsql stable security definer set search_path = website, public as $$
declare
  d jsonb := coalesce(old_data, jsonb_build_object(
    'unit', 'pcs', 'purchase_price', 0, 'opening_stock', 0, 'low_stock', 0, 'active', 1,
    'supplier', '', 'rack', '', 'images', '[]'::jsonb, 'images_removed', '[]'::jsonb));
  w jsonb := coalesce(d -> 'web', '{}'::jsonb);
  price bigint := round(coalesce(n.base_price, 0) * 100);
  first_color text;
begin
  begin
    first_color := (n.colors::jsonb) ->> 0;
  exception when others then
    first_color := null;
  end;
  d := d || jsonb_build_object(
    'name', coalesce(nullif(btrim(n.internal_name), ''), n.name),
    'sku', coalesce(n.sku, ''),
    'barcode', coalesce(n.barcode, ''),
    'category', coalesce(website.category_name(n.category_id), ''),
    'brand', coalesce(n.brand, ''),
    'material', coalesce(n.material, ''),
    'color', coalesce(first_color, ''),
    'description', coalesce(n.short_description, ''));
  if website.txt(d, 'rate_unit') is not null then
    d := d || jsonb_build_object('sale_rate', price);
  else
    d := d || jsonb_build_object('sale_price', price);
  end if;
  w := w || jsonb_build_object(
    'name', n.name,
    'visible', n.status = 'ACTIVE',
    'status', n.status,
    'long_description', n.long_description,
    'colors', n.colors,
    'sizes', n.sizes,
    'pattern', n.pattern,
    'collection_id', n.collection_id,
    'sub_category_id', n.sub_category_id,
    'discount_percentage', n.discount_percentage,
    'offer_price', n.offer_price,
    'length', n.length, 'width', n.width, 'height', n.height, 'weight', n.weight,
    'is_featured', coalesce(n.is_featured, false),
    'is_trending', coalesce(n.is_trending, false),
    'is_new_arrival', coalesce(n.is_new_arrival, false),
    'is_best_seller', coalesce(n.is_best_seller, false),
    'is_premium', coalesce(n.is_premium, false),
    'tags', n.tags,
    'meta_title', n.meta_title,
    'meta_description', n.meta_description,
    'meta_keywords', n.meta_keywords,
    'created_at', coalesce(w ->> 'created_at', coalesce(n.created_at, now() at time zone 'UTC')::text));
  return jsonb_set(d, '{web}', w);
end $$;

create or replace function website.products_write() returns trigger
language plpgsql security definer set search_path = website, public as $$
declare
  rid uuid;
  cur jsonb;
begin
  if tg_op = 'INSERT' then
    rid := gen_random_uuid();
    perform website.save_record(rid, 'item', website.product_data(new, null));
    new.id := website.web_id(rid);
    return new;
  end if;
  rid := website.rec_id(old.id);
  select data into cur from public.records where id = rid;
  if tg_op = 'UPDATE' then
    perform website.save_record(rid, 'item', website.product_data(new, cur));
    return new;
  end if;
  -- DELETE: the item is deleted in Hisaab too (phones keep it, made inactive, if it is on a bill)
  perform website.save_record(rid, 'item', cur, true);
  return old;
end $$;
drop trigger if exists products_write on website.products;
create trigger products_write instead of insert or update or delete on website.products
  for each row execute function website.products_write();

-- ---------------------------------------------------------------- product_variants = Hisaab sizes
create or replace view website.product_variants as
select
  i.id                                                  as id,
  website.txt(w, 'color')                               as color,
  website.txt(w, 'material')                            as material,
  round(coalesce(website.num(r.data, 'sale_price'), 0) / 100.0, 2) as price,
  coalesce(website.txt(w, 'size'), website.txt(r.data, 'name')) as size,
  coalesce(website.num(r.data, 'opening_stock'), 0)::integer as stock_quantity,
  p.id                                                  as product_id
from public.records r
join website.record_ids i on i.record_id = r.id
join website.record_ids p on p.record_id::text = r.data ->> 'item'
join public.records item on item.id = p.record_id and not item.deleted
cross join lateral (select coalesce(r.data -> 'web', '{}'::jsonb) as w) x
where r.business_id = website.biz() and r.kind = 'variant' and not r.deleted
  and coalesce(website.num(r.data, 'active'), 1) <> 0;

create or replace function website.variants_write() returns trigger
language plpgsql security definer set search_path = website, public as $$
declare
  rid uuid;
  cur jsonb;
  d jsonb;
begin
  if tg_op = 'DELETE' then
    rid := website.rec_id(old.id);
    select data into cur from public.records where id = rid;
    perform website.save_record(rid, 'variant', cur, true);
    return old;
  end if;
  if tg_op = 'INSERT' then
    rid := gen_random_uuid();
    cur := jsonb_build_object('purchase_price', 0, 'opening_stock', 0, 'low_stock', 0, 'active', 1,
                              'sort', 0, 'barcode', '', 'length', 0);
  else
    rid := website.rec_id(old.id);
    select data into cur from public.records where id = rid;
  end if;
  d := cur || jsonb_build_object(
    'item', website.rec_id(new.product_id)::text,
    'name', coalesce(nullif(concat_ws(' · ', nullif(btrim(new.size), ''), nullif(btrim(new.color), ''),
                                      nullif(btrim(new.material), '')), ''), 'Standard'),
    'sale_price', round(coalesce(new.price, 0) * 100));
  d := jsonb_set(d, '{web}', coalesce(cur -> 'web', '{}'::jsonb)
                             || jsonb_build_object('size', new.size, 'color', new.color, 'material', new.material));
  perform website.save_record(rid, 'variant', d);
  if tg_op = 'INSERT' then
    new.id := website.web_id(rid);
  end if;
  return new;
end $$;
drop trigger if exists variants_write on website.product_variants;
create trigger variants_write instead of insert or update or delete on website.product_variants
  for each row execute function website.variants_write();

-- ---------------------------------------------------------------- product_specifications = rows in item.web.specs
create or replace view website.product_specifications as
select
  (s.e ->> 'id')::bigint                                as id,
  website.flag(s.e, 'show', true)                       as show_to_customers,
  coalesce(website.num(s.e, 'sort'), s.n - 1)::integer  as sort_order,
  coalesce(s.e ->> 'key', '')::varchar(255)             as spec_key,
  coalesce(s.e ->> 'value', '')::varchar(255)           as spec_value,
  i.id                                                  as product_id
from public.records r
join website.record_ids i on i.record_id = r.id
cross join lateral jsonb_array_elements(
  case when jsonb_typeof(r.data -> 'web' -> 'specs') = 'array' then r.data -> 'web' -> 'specs' else '[]'::jsonb end
) with ordinality as s(e, n)
where r.business_id = website.biz() and r.kind = 'item' and not r.deleted;

create or replace function website.specs_write() returns trigger
language plpgsql security definer set search_path = website, public as $$
declare
  rid uuid;
  cur jsonb;
  specs jsonb;
  row_id bigint;
begin
  rid := website.rec_id(case when tg_op = 'INSERT' then new.product_id else old.product_id end);
  select data into cur from public.records where id = rid for update;
  specs := case when jsonb_typeof(cur -> 'web' -> 'specs') = 'array' then cur -> 'web' -> 'specs' else '[]'::jsonb end;
  row_id := case when tg_op = 'INSERT' then nextval('website.spec_ids') else old.id end;
  -- drop the old copy of this row (update / delete)
  select coalesce(jsonb_agg(e), '[]'::jsonb) into specs
  from jsonb_array_elements(specs) e where (e ->> 'id')::bigint is distinct from row_id;
  if tg_op <> 'DELETE' then
    specs := specs || jsonb_build_array(jsonb_build_object(
      'id', row_id, 'key', new.spec_key, 'value', new.spec_value,
      'sort', coalesce(new.sort_order, 0), 'show', coalesce(new.show_to_customers, true)));
  end if;
  perform website.save_record(rid, 'item',
    jsonb_set(cur, '{web}', coalesce(cur -> 'web', '{}'::jsonb) || jsonb_build_object('specs', specs)));
  if tg_op = 'DELETE' then
    return old;
  end if;
  new.id := row_id;
  return new;
end $$;
drop trigger if exists specs_write on website.product_specifications;
create trigger specs_write instead of insert or update or delete on website.product_specifications
  for each row execute function website.specs_write();

